import { expect, test, type Page } from "@playwright/test";

let counter = 0;
const unique = (): string =>
  `${Date.now().toString(36)}${counter++}${Math.random().toString(36).slice(2, 6)}`;

// A signed-in owner with a new game of `names` entries; opens its editor on the Answers tab
async function openAnswers(
  page: Page,
  names: string[],
): Promise<{ slug: string; ids: number[] }> {
  await page.request.post("/api/test/login", {
    data: { email: `answers-${unique()}@example.test` },
  });
  const created = await page.request.post("/api/games", {
    data: { name: `Answers ${unique()}` },
  });
  const { slug } = (await created.json()) as { slug: string };
  const ids: number[] = [];
  for (const name of names) {
    const res = await page.request.post(`/api/games/${slug}/entries`, {
      data: { name },
    });
    ids.push(((await res.json()) as { id: number }[]).at(-1)!.id);
  }
  await page.goto(`/g/${slug}/edit`);
  await expect(page.locator("#loading-state")).toBeHidden();
  await page.locator("#tab-answers").click();
  return { slug, ids };
}

test("the Answers tab lists real dates and overrides, edits and clears a future day", async ({
  page,
}) => {
  await openAnswers(page, ["Rex", "Fido", "Bella", "Max"]);
  const rows = page.locator("#ans-days tr");
  // A new game starts today: no history yet, then today and six more days
  await expect(rows).toHaveCount(7);
  await expect(rows.first()).toContainText("today");
  await expect(rows.first().locator("td").first()).toHaveText(
    /^\d{4}-\d{2}-\d{2}$/,
  );
  await expect(rows.first().locator("button")).toBeVisible();

  const target = rows.nth(2);
  await target.locator("button").click();
  await expect(page.locator("#override-warning")).toBeVisible();
  const current = await target.locator("td").nth(1).innerText();
  const other = ["Rex", "Fido", "Bella", "Max"].find((n) => n !== current)!;
  await page.locator("#override-entry").selectOption({ label: other });
  await page.locator("#override-save").click();
  await expect(target).toContainText(other);
  await expect(target).toContainText("override");
  await expect(target.locator("button")).toHaveText("EDIT / CLEAR");

  // It survives a reload
  await page.reload();
  await expect(page.locator("#loading-state")).toBeHidden();
  await page.locator("#tab-answers").click();
  await expect(rows.nth(2)).toContainText("override");

  await rows.nth(2).locator("button").click();
  await page.locator("#override-clear").click();
  await expect(rows.nth(2)).toContainText("autogenerated");
});

test("deleting an entry that is a future override clears the override", async ({
  page,
}) => {
  const { slug, ids } = await openAnswers(page, ["Rex", "Fido", "Bella"]);
  const rows = page.locator("#ans-days tr");
  await expect(rows).toHaveCount(7);
  const date = (await rows.nth(3).locator("td").first().innerText()).trim();
  const put = await page.request.put(`/api/games/${slug}/answers/${date}`, {
    data: { entryId: ids[0] },
  });
  expect(put.status()).toBe(200);
  const gone = await page.request.delete(
    `/api/games/${slug}/entries/${ids[0]}`,
    { data: {} },
  );
  expect(gone.status()).toBe(200);
  await page.locator("#tab-details").click();
  await page.locator("#tab-answers").click();
  await expect(rows.nth(3)).toContainText("autogenerated");
  await expect(rows.nth(3)).not.toContainText("Rex");
});

test("a game without entries asks for entries first", async ({ page }) => {
  await openAnswers(page, []);
  await expect(page.locator("#ans-message")).toContainText("Add entries first");
  await expect(page.locator("#ans-days tr")).toHaveCount(0);
});

test("the skip period is limited to N-1 and saved", async ({ page }) => {
  await openAnswers(page, ["Rex", "Fido", "Bella", "Max"]);
  await page.locator("#tab-details").click();
  await expect(page.locator("#edit-skip")).toHaveAttribute("max", "3");
  await page.locator("#edit-skip").fill("2");
  await page.getByRole("button", { name: "Save" }).click();
  await expect(page.locator("#edit-saved")).toHaveText("Saved.");
  await page.locator("#edit-skip").fill("4");
  await page.getByRole("button", { name: "Save" }).click();
  await expect(page.locator("#edit-error")).not.toBeEmpty();
  // The days still load after the re-draw
  await page.locator("#tab-answers").click();
  await expect(page.locator("#ans-days tr")).toHaveCount(7);
});
