// The editor's Answers tab: Answer History and Overrides by real calendar date.
import { api, errorText } from "../manage-client.ts";

const $ = <T extends HTMLElement>(selector: string): T =>
  document.querySelector<T>(selector)!;

interface AnswerDay {
  date: string;
  entryId: number;
  name: string | null;
  source: "generated" | "override";
  today: boolean;
  locked: boolean;
  missing: boolean;
  previous: number[];
}
interface AnswerList {
  today: string;
  from: string;
  to: string;
  days: AnswerDay[];
}

const HISTORY_DAYS = 7;

const cell = (...children: (Node | string)[]): HTMLTableCellElement => {
  const td = document.createElement("td");
  td.append(...children);
  return td;
};

// Colored pill; the color comes from [data-tag] in styles.css
const pill = (text: string): HTMLSpanElement => {
  const span = document.createElement("span");
  span.className = "tag";
  span.dataset["tag"] = text;
  span.textContent = text;
  return span;
};

// Returns a refresh to call when the tab opens
export function initAnswers(base: string): () => Promise<void> {
  const from = $<HTMLInputElement>("#ans-from");
  const to = $<HTMLInputElement>("#ans-to");
  const message = $("#ans-message");
  const tbody = $("#ans-days");
  const form = $<HTMLFormElement>("#override-form");
  const pick = $<HTMLSelectElement>("#override-entry");
  const notice = $("#override-notice");
  const clearButton = $<HTMLButtonElement>("#override-clear");
  let days: AnswerDay[] = [];
  let editing: AnswerDay | null = null;

  const say = (text: string | null): void => {
    message.textContent = text ?? "";
    message.hidden = text === null;
  };

  const updateNotice = (): void => {
    notice.hidden =
      editing === null || !editing.previous.includes(Number(pick.value));
  };
  const openEditor = (day: AnswerDay): void => {
    editing = day;
    $("#override-title").textContent = `Override ${day.date}`;
    pick.value = String(day.missing ? pick.options[0]?.value : day.entryId);
    clearButton.hidden = day.source !== "override";
    updateNotice();
    form.hidden = false;
  };
  pick.onchange = updateNotice;

  const render = (): void => {
    tbody.replaceChildren(
      ...days.map((day) => {
        const row = document.createElement("tr");
        row.dataset["date"] = day.date;
        const tags = cell(
          ...(day.today ? [pill("today")] : []),
          day.source === "override" ? pill("override") : pill("autogenerated"),
        );
        const action = cell();
        if (day.locked) {
          const locked = document.createElement("span");
          locked.className = "action-locked";
          locked.textContent = "locked";
          action.append(locked);
        } else {
          const edit = document.createElement("button");
          edit.type = "button";
          edit.className = "override-edit";
          edit.textContent =
            day.source === "override" ? "EDIT / CLEAR" : "OVERRIDE";
          edit.onclick = (): void => openEditor(day);
          action.append(edit);
        }
        row.append(
          cell(day.date),
          cell(day.missing ? `MISSING (${day.entryId})` : day.name!),
          tags,
          action,
        );
        return row;
      }),
    );
  };

  const load = async (query: string): Promise<AnswerList | null> => {
    const out = await api<AnswerList>("GET", `${base}/answers${query}`);
    if (out?.status !== 200) {
      say(
        out?.status === 400 ? "Check the range and try again." : errorText(out),
      );
      return null;
    }
    return out.data;
  };
  const show = (data: AnswerList): void => {
    say(null);
    from.value = data.from;
    to.value = data.to;
    days = data.days;
    form.hidden = true;
    render();
  };
  // Saving or clearing re-draws later days, so reload the same range afterwards
  const reload = async (): Promise<void> => {
    const data = await load(`?from=${from.value}&to=${to.value}`);
    if (data) {
      show(data);
    }
  };

  const apply = async (
    method: "PUT" | "DELETE",
    body: unknown,
  ): Promise<void> => {
    const out = await api(method, `${base}/answers/${editing!.date}`, body);
    if (out?.status !== 200) {
      say(errorText(out));
      return;
    }
    await reload();
  };
  form.onsubmit = (event): void => {
    event.preventDefault();
    void apply("PUT", { entryId: Number(pick.value) });
  };
  clearButton.onclick = (): void => void apply("DELETE", {});
  $("#override-cancel").onclick = (): void => {
    form.hidden = true;
  };
  $<HTMLFormElement>("#ans-range").onsubmit = (event): void => {
    event.preventDefault();
    void reload();
  };

  return async () => {
    form.hidden = true;
    const roster = await api<{ entries?: { id: number; name: string }[] }>(
      "GET",
      base,
    );
    const entries = roster?.data.entries ?? [];
    pick.replaceChildren(
      ...entries.map((e) => new Option(e.name, String(e.id))),
    );
    $("#ans-body").hidden = entries.length === 0;
    if (entries.length === 0) {
      say("Add entries first: answers are drawn from them.");
      return;
    }
    say("Loading days…");
    // One call finds today, a second adds the days before it as the Answer History
    const first = await load("");
    if (first) {
      const [y, m, d] = first.today.split("-").map(Number) as [
        number,
        number,
        number,
      ];
      const start = new Date(Date.UTC(y, m - 1, d - HISTORY_DAYS))
        .toISOString()
        .slice(0, 10);
      show((await load(`?from=${start}&to=${first.to}`)) ?? first);
    }
  };
}
