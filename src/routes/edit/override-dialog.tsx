// The Answers tab's popup for overriding one day: search the entries by name, tap one, save.
import { useState, type FormEvent } from "react";
import { Alert } from "../../components/ui/alert.tsx";
import { Button } from "../../components/ui/button.tsx";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogTitle,
} from "../../components/ui/dialog.tsx";
import { Input } from "../../components/ui/input.tsx";
import { cn } from "../../lib/utils.ts";

export interface Choice {
  id: number;
  name: string;
  // The entry's picture, "" when it has none
  thumb: string;
}

export function OverrideDialog({
  date,
  isOverride,
  choices,
  pick,
  onPick,
  recent,
  error,
  onSave,
  onClear,
  onClose,
}: {
  date: string;
  // The day already has an Override, so it can be cleared
  isOverride: boolean;
  choices: readonly Choice[];
  pick: number | null;
  onPick: (id: number) => void;
  // Entries that were the answer in the days just before
  recent: readonly number[];
  error: string | null;
  onSave: () => void;
  onClear: () => void;
  onClose: () => void;
}) {
  const [query, setQuery] = useState("");
  const lower = query.trim().toLowerCase();
  const shown = choices.filter((choice) =>
    choice.name.toLowerCase().includes(lower),
  );

  const submit = (event: FormEvent): void => {
    event.preventDefault();
    onSave();
  };

  return (
    <Dialog
      open
      onOpenChange={(open) => {
        if (!open) {
          onClose();
        }
      }}
    >
      <DialogContent id="override-form" className="max-w-lg">
        <form className="grid min-h-0 gap-4" onSubmit={submit}>
          <DialogTitle id="override-title" className="pr-8 text-xl">
            Override {date}
          </DialogTitle>
          <DialogDescription id="override-warning">
            Saving re-draws every later autogenerated day. Overrides stay.
          </DialogDescription>
          <Input
            id="override-search"
            type="search"
            placeholder="Search entries"
            aria-label="Search entries"
            autoComplete="off"
            value={query}
            onChange={(event) => setQuery(event.target.value)}
          />
          <ul
            id="override-entries"
            role="listbox"
            aria-label="Answer"
            className="max-h-[45dvh] divide-y overflow-y-auto rounded-lg border"
          >
            {shown.map((choice) => (
              <li
                key={choice.id}
                role="option"
                aria-selected={choice.id === pick}
                tabIndex={0}
                className={cn(
                  "override-choice flex cursor-pointer items-center gap-3 px-3 py-2 hover:bg-muted focus-visible:bg-muted focus-visible:outline-none",
                  choice.id === pick &&
                    "bg-primary/15 font-semibold hover:bg-primary/15",
                )}
                onClick={() => onPick(choice.id)}
                onKeyDown={(event) => {
                  if (event.key === "Enter" || event.key === " ") {
                    event.preventDefault();
                    onPick(choice.id);
                  }
                }}
              >
                {choice.thumb ? (
                  <img
                    className="size-10 shrink-0 rounded-md object-cover"
                    src={choice.thumb}
                    alt=""
                  />
                ) : (
                  <span
                    className="size-10 shrink-0 rounded-md bg-muted"
                    aria-hidden="true"
                  />
                )}
                <span className="min-w-0 flex-1 truncate">{choice.name}</span>
              </li>
            ))}
            {shown.length === 0 && (
              <li className="px-3 py-4 text-center text-sm text-muted-foreground">
                No entries match.
              </li>
            )}
          </ul>
          {pick !== null && recent.includes(pick) && (
            <Alert id="override-notice" variant="warn">
              This entry appeared in the days just before.
            </Alert>
          )}
          {error && (
            <Alert id="override-error" variant="warn" role="alert">
              {error}
            </Alert>
          )}
          <div className="flex flex-wrap gap-2">
            <Button type="submit" id="override-save" disabled={pick === null}>
              Save override
            </Button>
            {isOverride && (
              <Button
                type="button"
                id="override-clear"
                variant="secondary"
                onClick={onClear}
              >
                Clear override
              </Button>
            )}
            <Button
              type="button"
              id="override-cancel"
              variant="ghost"
              onClick={onClose}
            >
              Cancel
            </Button>
          </div>
        </form>
      </DialogContent>
    </Dialog>
  );
}
