// The editor's Answers tab: Answer History and Overrides by real calendar date.
import { useEffect, useState } from "react";
import { Alert } from "../../components/ui/alert.tsx";
import {
  AlertDialog,
  AlertDialogAction,
  AlertDialogCancel,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogTitle,
} from "../../components/ui/alert-dialog.tsx";
import { Badge } from "../../components/ui/badge.tsx";
import { Button } from "../../components/ui/button.tsx";
import { Input, Label } from "../../components/ui/input.tsx";
import {
  Table,
  TableCell,
  TableHead,
  TableRow,
} from "../../components/ui/table.tsx";
import { useDelayed } from "../../lib/use-delayed.ts";
import { api, errorText } from "../../manage-client.ts";
import { OverrideDialog, type Choice } from "./override-dialog.tsx";
import { thumbOf, type Attribute, type Entry } from "./types.ts";

interface AnswerDay {
  date: string;
  entryId: number;
  name: string | null;
  source: "generated" | "override";
  today: boolean;
  locked: boolean;
  missing: boolean;
  previous: number[];
}
interface AnswerList {
  today: string;
  from: string;
  to: string;
  days: AnswerDay[];
  // The entries an Override may name (a Sequence game's with every photo); all when absent
  answerIds?: number[];
}

const HISTORY_DAYS = 7;

const TAG_VARIANTS = {
  today: "default",
  override: "warn",
  autogenerated: "secondary",
} as const;

function Tag({ tag }: { tag: keyof typeof TAG_VARIANTS }) {
  return (
    <Badge className="tag" data-tag={tag} variant={TAG_VARIANTS[tag]}>
      {tag}
    </Badge>
  );
}

// The day before `today` minus the history, as YYYY-MM-DD
function historyStart(today: string): string {
  const [y, m, d] = today.split("-").map(Number) as [number, number, number];
  return new Date(Date.UTC(y, m - 1, d - HISTORY_DAYS))
    .toISOString()
    .slice(0, 10);
}

export function AnswersPanel({
  base,
  active,
}: {
  base: string;
  // The tab is open: reload the roster and the days
  active: boolean;
}) {
  const [message, setMessage] = useState<string | null>(null);
  // The first load of the days; its notice waits in case the days arrive at once
  const [loading, setLoading] = useState(false);
  const slow = useDelayed(loading);
  const [entries, setEntries] = useState<Choice[]>([]);
  const [from, setFrom] = useState("");
  const [to, setTo] = useState("");
  const [days, setDays] = useState<AnswerDay[]>([]);
  const [answerIds, setAnswerIds] = useState<number[] | null>(null);
  const choices = entries.filter(
    (entry) => answerIds === null || answerIds.includes(entry.id),
  );
  const [editing, setEditing] = useState<AnswerDay | null>(null);
  const [pick, setPick] = useState<number | null>(null);
  // A change to today's answer waiting for the owner to confirm the restart
  const [confirming, setConfirming] = useState<"PUT" | "DELETE" | null>(null);

  const load = async (query: string): Promise<AnswerList | null> => {
    const out = await api<AnswerList>("GET", `${base}/answers${query}`);
    if (out?.status !== 200) {
      setMessage(
        out?.status === 400 ? "Check the range and try again." : errorText(out),
      );
      return null;
    }
    return out.data;
  };
  const show = (data: AnswerList): void => {
    setMessage(null);
    setFrom(data.from);
    setTo(data.to);
    setDays(data.days);
    setAnswerIds(data.answerIds ?? null);
    setEditing(null);
  };
  // Saving or clearing re-draws later days, so reload the same range afterwards
  const reload = async (): Promise<void> => {
    const data = await load(`?from=${from}&to=${to}`);
    if (data) {
      show(data);
    }
  };

  useEffect(() => {
    if (!active) {
      return;
    }
    void (async () => {
      const [roster, attributes] = await Promise.all([
        api<Entry[]>("GET", `${base}/entries`),
        api<Attribute[]>("GET", `${base}/attributes`),
      ]);
      const list = (roster?.status === 200 ? roster.data : []).map((entry) => ({
        id: entry.id,
        name: entry.name,
        thumb: thumbOf(
          entry,
          attributes?.status === 200 ? attributes.data : [],
        ),
      }));
      setEntries(list);
      if (list.length === 0) {
        setMessage("Add entries first: answers are drawn from them.");
        return;
      }
      setMessage(null);
      setLoading(true);
      // One call finds today, a second adds the days before it as the Answer History
      const out = await api<AnswerList>("GET", `${base}/answers`);
      if (out?.status !== 200) {
        setLoading(false);
        setMessage(errorText(out));
        return;
      }
      const first = out.data;
      const full = await api<AnswerList>(
        "GET",
        `${base}/answers?from=${historyStart(first.today)}&to=${first.to}`,
      );
      setLoading(false);
      show(full?.status === 200 ? full.data : first);
    })();
  }, [active, base]);

  const openEditor = (day: AnswerDay): void => {
    setEditing(day);
    setMessage(null);
    setPick(day.missing ? null : day.entryId);
  };

  const apply = async (
    method: "PUT" | "DELETE",
    body: unknown,
  ): Promise<void> => {
    const out = await api(method, `${base}/answers/${editing!.date}`, body);
    if (out?.status !== 200) {
      setMessage(errorText(out));
      return;
    }
    await reload();
  };

  const save = (method: "PUT" | "DELETE"): void => {
    void apply(method, method === "PUT" ? { entryId: pick } : {});
  };
  // Changing today's answer restarts the day for every player, so it asks first
  const saveOrAsk = (method: "PUT" | "DELETE"): void => {
    const changesToday =
      editing!.today && (method === "DELETE" || pick !== editing!.entryId);
    if (changesToday) {
      setConfirming(method);
    } else {
      save(method);
    }
  };

  return (
    <div className="space-y-5">
      <p className="lede text-sm text-muted-foreground">
        One answer per calendar date, the same for every player. Past days are
        locked; you can override today or a later day.
      </p>
      <Alert
        id="ans-message"
        variant="warn"
        role="status"
        hidden={message === null && !slow}
      >
        {message ?? (slow ? "Loading days…" : null)}
      </Alert>
      <div id="ans-body" className="space-y-5" hidden={entries.length === 0}>
        <form
          id="ans-range"
          className="range-form flex flex-wrap items-end gap-3"
          onSubmit={(event) => {
            event.preventDefault();
            void reload();
          }}
        >
          <Label className="grid gap-2">
            From
            <Input
              type="date"
              id="ans-from"
              value={from}
              onChange={(event) => setFrom(event.target.value)}
            />
          </Label>
          <Label className="grid gap-2">
            To
            <Input
              type="date"
              id="ans-to"
              value={to}
              onChange={(event) => setTo(event.target.value)}
            />
          </Label>
          <Button type="submit" variant="secondary">
            Show days
          </Button>
        </form>
        <Table>
          <thead>
            <tr>
              <TableHead>Date</TableHead>
              <TableHead>Answer</TableHead>
              <TableHead>Source</TableHead>
              <TableHead>
                <span className="sr-only">Action</span>
              </TableHead>
            </tr>
          </thead>
          <tbody id="ans-days">
            {days.map((day) => (
              // Every row the same height, the last included (issue #83)
              <TableRow
                key={day.date}
                data-date={day.date}
                className="last:border-b"
              >
                <TableCell className="font-mono whitespace-nowrap">
                  {day.date}
                </TableCell>
                <TableCell>
                  {day.missing ? `MISSING (${day.entryId})` : day.name}
                </TableCell>
                <TableCell>
                  {/* Pills and action stay on one line, so rows stay even on phones (the table scrolls) */}
                  <span className="flex gap-1 whitespace-nowrap">
                    {day.today && <Tag tag="today" />}
                    <Tag
                      tag={
                        day.source === "override" ? "override" : "autogenerated"
                      }
                    />
                  </span>
                </TableCell>
                <TableCell className="text-right whitespace-nowrap">
                  {day.locked ? (
                    <span className="action-locked inline-flex h-8 items-center text-xs text-muted-foreground">
                      locked
                    </span>
                  ) : (
                    <Button
                      className="override-edit"
                      variant="outline"
                      size="sm"
                      onClick={() => openEditor(day)}
                    >
                      {day.source === "override" ? "EDIT / CLEAR" : "OVERRIDE"}
                    </Button>
                  )}
                </TableCell>
              </TableRow>
            ))}
          </tbody>
        </Table>
        {editing && (
          <OverrideDialog
            date={editing.date}
            isOverride={editing.source === "override"}
            choices={choices}
            pick={pick}
            onPick={setPick}
            recent={editing.previous}
            error={message}
            onSave={() => saveOrAsk("PUT")}
            onClear={() => saveOrAsk("DELETE")}
            onClose={() => setEditing(null)}
          />
        )}
      </div>
      <AlertDialog
        open={confirming !== null}
        onOpenChange={(open) => {
          if (!open) {
            setConfirming(null);
          }
        }}
      >
        <AlertDialogContent id="restart-dialog">
          <AlertDialogTitle>Change today's answer?</AlertDialogTitle>
          <AlertDialogDescription>
            {confirming === "DELETE"
              ? "If the re-drawn answer is a different entry, every"
              : "Every"}{" "}
            player's guesses and today's stats for this game are reset, and
            everyone starts today over. This can't be undone.
          </AlertDialogDescription>
          <AlertDialogFooter>
            <AlertDialogCancel>Cancel</AlertDialogCancel>
            <AlertDialogAction
              value="confirm"
              onClick={() => save(confirming!)}
            >
              {confirming === "DELETE" ? "Clear override" : "Save override"}
            </AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </div>
  );
}
