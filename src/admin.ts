// Admin panel (Answers tab): peek at stored Daily Answers and override them.
import { GUESS_DATA } from "./game/roster.ts";

interface AnswerDay {
  date: string;
  petId: string;
  name: string | null;
  source: "generated" | "override";
  today: boolean;
  locked: boolean;
  missing: boolean;
  previous: string[];
}

interface AdminUser {
  id: number;
  name: string;
  email: string;
  lastSeen: string;
  admin: boolean;
}

type BackupStatus =
  | { state: "error"; message: string }
  | {
      state: "ok" | "red";
      reasons: string[];
      newestDump: string | null;
      lastRestore: { ok: boolean; error?: string } | null;
    };

const $ = <T extends HTMLElement>(selector: string): T =>
  document.querySelector<T>(selector)!;

async function call(
  method: string,
  url: string,
  body?: unknown,
): Promise<{ ok: boolean; json: unknown }> {
  try {
    const res = await fetch(url, {
      method,
      headers: { "Content-Type": "application/json" },
      ...(body !== undefined && { body: JSON.stringify(body) }),
    });
    return { ok: res.ok, json: await res.json().catch(() => ({})) };
  } catch {
    return { ok: false, json: {} };
  }
}

export function initAdmin(): (admin: boolean) => void {
  const dialog = $<HTMLDialogElement>("#admin-dialog");
  const button = $<HTMLButtonElement>("#admin-button");
  const from = $<HTMLInputElement>("#admin-from");
  const to = $<HTMLInputElement>("#admin-to");
  const message = $<HTMLElement>("#admin-message");
  const tbody = $<HTMLElement>("#admin-days");
  const form = $<HTMLFormElement>("#override-form");
  const pet = $<HTMLSelectElement>("#override-pet");
  const notice = $<HTMLElement>("#override-notice");
  const clearButton = $<HTMLButtonElement>("#override-clear");
  let days: AnswerDay[] = [];
  let editing: AnswerDay | null = null;

  for (const { id, name } of GUESS_DATA) {
    pet.append(new Option(name, id));
  }
  const say = (text: string | null): void => {
    message.textContent = text ?? "";
    message.hidden = text === null;
  };

  const show = async (query = ""): Promise<void> => {
    form.hidden = true;
    const { ok, json } = await call("GET", `/api/admin/answers${query}`);
    if (!ok) {
      say("Could not load the days. Check the range and try again.");
      return;
    }
    const data = json as { from: string; to: string; days: AnswerDay[] };
    say(null);
    from.value = data.from;
    to.value = data.to;
    days = data.days;
    render();
  };

  const render = (): void => {
    tbody.replaceChildren(
      ...days.map((day) => {
        const row = document.createElement("tr");
        row.dataset["date"] = day.date;
        const cell = (text: string): void => {
          row.append(
            Object.assign(document.createElement("td"), { textContent: text }),
          );
        };
        cell(day.date);
        cell(day.missing ? `MISSING (${day.petId})` : day.name!);
        cell(
          [
            day.today ? "today" : "",
            day.source === "override" ? "override" : "autogenerated",
          ]
            .filter(Boolean)
            .join(" "),
        );
        const action = document.createElement("td");
        if (day.locked) {
          action.textContent = "locked";
        } else {
          const edit = document.createElement("button");
          edit.type = "button";
          edit.className = "override-edit";
          edit.textContent =
            day.source === "override" ? "EDIT / CLEAR" : "OVERRIDE";
          edit.onclick = (): void => openEditor(day);
          action.append(edit);
        }
        row.append(action);
        return row;
      }),
    );
  };

  const updateNotice = (): void => {
    notice.hidden = editing === null || !editing.previous.includes(pet.value);
  };
  const openEditor = (day: AnswerDay): void => {
    editing = day;
    $<HTMLElement>("#override-title").textContent = `Override ${day.date}`;
    pet.value = day.missing ? GUESS_DATA[0]!.id : day.petId;
    clearButton.hidden = day.source !== "override";
    updateNotice();
    form.hidden = false;
  };
  pet.onchange = updateNotice;

  // Saving or clearing re-draws later days, so reload the same range afterwards
  const reload = (): Promise<void> =>
    show(`?from=${from.value}&to=${to.value}`);
  const apply = async (method: string, body?: unknown): Promise<void> => {
    const { ok } = await call(
      method,
      `/api/admin/answers/${editing!.date}`,
      body ?? {},
    );
    if (!ok) {
      say("Could not save that day.");
      return;
    }
    await reload();
  };
  form.onsubmit = (event): void => {
    event.preventDefault();
    void apply("PUT", { petId: pet.value });
  };
  clearButton.onclick = (): void => void apply("DELETE");
  $<HTMLButtonElement>("#override-cancel").onclick = (): void => {
    form.hidden = true;
  };
  $<HTMLFormElement>("#admin-range").onsubmit = (event): void => {
    event.preventDefault();
    void reload();
  };
  const usersPanel = $<HTMLElement>("#users-panel");
  const answersPanel = $<HTMLElement>("#answers-panel");
  const usersMessage = $<HTMLElement>("#users-message");
  const usersBody = $<HTMLElement>("#admin-users");

  const showUsers = async (): Promise<void> => {
    const { ok, json } = await call("GET", "/api/admin/users");
    if (!ok) {
      usersMessage.textContent = "Could not load the users.";
      usersMessage.hidden = false;
      return;
    }
    usersMessage.hidden = true;
    const data = json as { users: AdminUser[]; self: number };
    const admins = data.users.filter((user) => user.admin).length;
    usersBody.replaceChildren(
      ...data.users.map((user) => {
        const row = document.createElement("tr");
        row.dataset["email"] = user.email;
        const cell = (text: string): void => {
          row.append(
            Object.assign(document.createElement("td"), { textContent: text }),
          );
        };
        cell(user.name);
        cell(user.email);
        cell(new Date(user.lastSeen).toLocaleString());
        cell(user.admin ? "admin" : "player");
        const toggle = document.createElement("button");
        toggle.type = "button";
        toggle.className = "role-toggle";
        toggle.textContent = user.admin ? "DEMOTE" : "PROMOTE";
        // The server enforces both guards too; the button just shows them
        toggle.disabled = user.admin && (user.id === data.self || admins <= 1);
        toggle.onclick = async (): Promise<void> => {
          const res = await call("PUT", `/api/admin/users/${user.id}`, {
            admin: !user.admin,
          });
          if (!res.ok) {
            usersMessage.textContent = "Could not change that role.";
            usersMessage.hidden = false;
            return;
          }
          await showUsers();
        };
        const action = document.createElement("td");
        action.append(toggle);
        row.append(action);
        return row;
      }),
    );
  };

  const backupPanel = $<HTMLElement>("#backup-panel");
  const showBackup = async (): Promise<void> => {
    const line = $<HTMLElement>("#backup-status");
    const reasons = $<HTMLElement>("#backup-reasons");
    const { ok, json } = await call("GET", "/api/admin/backup");
    const data = json as BackupStatus;
    const problems = !ok
      ? ["Could not load the backup status."]
      : data.state === "error"
        ? [data.message]
        : data.reasons;
    if (ok && data.state !== "error" && data.lastRestore?.error) {
      problems.push(`Restore error: ${data.lastRestore.error}`);
    }
    const newest = ok && data.state !== "error" ? data.newestDump : null;
    line.textContent = newest
      ? `Newest dump: ${((Date.now() - Date.parse(newest)) / 3600e3).toFixed(1)} hours ago`
      : "Newest dump: none";
    line.dataset["state"] = ok && data.state === "ok" ? "ok" : "red";
    reasons.replaceChildren(
      ...problems.map((text) =>
        Object.assign(document.createElement("li"), { textContent: text }),
      ),
    );
  };

  const tabs = {
    answers: $<HTMLElement>("#tab-answers"),
    users: $<HTMLElement>("#tab-users"),
    backup: $<HTMLElement>("#tab-backup"),
  };
  const selectTab = (name: "answers" | "users" | "backup"): void => {
    answersPanel.hidden = name !== "answers";
    usersPanel.hidden = name !== "users";
    backupPanel.hidden = name !== "backup";
    for (const [key, tab] of Object.entries(tabs)) {
      tab.ariaSelected = String(key === name);
    }
    void (name === "answers"
      ? show()
      : name === "users"
        ? showUsers()
        : showBackup());
  };
  tabs.answers.onclick = (): void => selectTab("answers");
  tabs.users.onclick = (): void => selectTab("users");
  tabs.backup.onclick = (): void => selectTab("backup");
  button.onclick = (): void => {
    dialog.showModal();
    selectTab("answers");
  };
  return (admin) => {
    button.hidden = !admin;
  };
}
